import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { spawn } from "node:child_process";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const crateDir = resolve(root, "wasm-kernels");
const wasmPath = resolve(crateDir, "target/wasm32-unknown-unknown/release/heliopause_engine_wasm_kernels.wasm");
const outputPath = resolve(root, "src/runner/cpu/wasm-kernels.generated.ts");

await run("cargo", ["build", "--release", "--target", "wasm32-unknown-unknown"], {
  cwd: crateDir,
  env: {
    ...process.env,
    RUSTFLAGS: `${process.env.RUSTFLAGS ?? ""} -C target-feature=+simd128`.trim(),
  },
});

const wasm = await readFile(wasmPath);
const base64 = wasm.toString("base64");
await writeFile(
  outputPath,
  `// Generated by scripts/build-wasm-kernels.mjs. Do not edit by hand.\n` +
    `export const PREFILL_WASM_SIMD_BASE64 = "${base64}";\n`,
);

function run(command, args, options) {
  return new Promise((resolveRun, reject) => {
    const child = spawn(command, args, {
      ...options,
      stdio: "inherit",
    });
    child.on("error", reject);
    child.on("exit", (code) => {
      if (code === 0) {
        resolveRun();
      } else {
        reject(new Error(`${command} ${args.join(" ")} exited with ${code}`));
      }
    });
  });
}
